/**
 * Builds the English DEMONSTRATION audio fixture (macOS only: uses `say` and `afconvert`).
 *
 * This is a synthetic computer voice reading text that already exists in src/data/cropsLibrary.ts.
 * It is a test fixture to prove offline audio works. It is NOT a recorded lesson and must
 * never be presented as one. Real Kpelle, Bassa and Mano recordings are added later by dropping
 * files into public/audio/<lang>/ and adding entries in src/data/audioLessons.ts.
 *
 * Run: npx tsx scripts/make-audio-fixture.ts
 */
import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {CROPS_LIBRARY} from '../src/data/cropsLibrary.ts';

const rice = CROPS_LIBRARY.find((c) => c.slug === 'rice')!;
const script = [rice.overview, ...rice.plantingInfo.slice(0, 2), `Safety note. ${rice.safetyDisclaimer}`].join(' ');

const outDir = path.resolve('public/audio/en');
fs.mkdirSync(outDir, {recursive: true});
const aiff = path.join(outDir, 'rice-planting-demo.aiff');
const m4a = path.join(outDir, 'rice-planting-demo.m4a');
execFileSync('say', ['-v', 'Samantha', '-r', '165', '-o', aiff, script]);
execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '24000', '-c', '1', aiff, m4a]);
fs.rmSync(aiff);

const info = execFileSync('afinfo', [m4a]).toString();
const duration = Math.round(Number(/estimated duration: ([\d.]+)/.exec(info)?.[1] ?? 0));
const bytes = fs.statSync(m4a).size;

fs.writeFileSync(
  path.resolve('src/data/audioFixtures.generated.ts'),
  `// GENERATED by scripts/make-audio-fixture.ts - do not edit by hand.\n` +
    `export const RICE_DEMO_FIXTURE = ${JSON.stringify({bytes, durationSec: duration, transcript: script}, null, 2)};\n`
);
console.log({m4a, bytes, duration});
